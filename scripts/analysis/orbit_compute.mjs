// Prints every number /research/data-centers-in-space/ quotes, from the same model the calculator runs
// (site/js/widgets/orbit-compute-core.mjs). Output: docs/specs/space-data-centers-output.txt.
// --write-diagrams also regenerates the three page diagrams in site/diagrams/ (oc-*.svg). --check fails if they are stale.
// Run: node scripts/analysis/orbit_compute.mjs [--write-diagrams | --check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as oc from '../../site/js/widgets/orbit-compute-core.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = new Set(process.argv.slice(2));
const lines = [];
const out = (s = '') => lines.push(s);
const n0 = (x) => Math.round(x).toLocaleString('en-US');
const n1 = (x) => x.toLocaleString('en-US', { minimumFractionDigits: 1, maximumFractionDigits: 1 });
const n2 = (x) => x.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const n3 = (x) => x.toLocaleString('en-US', { minimumFractionDigits: 3, maximumFractionDigits: 3 });

out('Orbital compute model: numbers for /research/data-centers-in-space/');
out('Generated by node scripts/analysis/orbit_compute.mjs from site/js/widgets/orbit-compute-core.mjs');
out('');

out('1. Capital recovery factors (10 %)');
for (const n of [5, 10, 12, 15, 20, 30]) out(`   CRF(10 %, ${n}) = ${oc.crf(0.1, n).toFixed(4)}`);
out(`   CRF(6 %, 12) = ${oc.crf(0.06, 12).toFixed(4)}; CRF(6 %, 20) = ${oc.crf(0.06, 20).toFixed(4)}; CRF(6 %, 30) = ${oc.crf(0.06, 30).toFixed(4)}`);
out('');

out('2. Radiators (two-sided panel, sink 0 K)');
for (const [t, e] of [[300, 1], [400, 1], [330, 0.9], [348, 0.9], [400, 0.9], [450, 0.9]]) {
  const f = oc.radiatorFlux(t, e);
  const a = oc.radiatorAreaPerKw(t, e);
  out(`   ${t} K, e ${e}: ${n0(f)} W/m2 of panel; ${n3(a)} m2 per kW = ${n2(a)} km2 per GW = ${n0(a * 1000)} m2 per MW; at 5 kg/m2 ${n2(a * 5)} kg/kW, at 15 kg/m2 ${n2(a * 15)} kg/kW`);
}
out(`   Area ratio 330 K to 400 K: ${n2(oc.radiatorAreaPerKw(330, 0.9) / oc.radiatorAreaPerKw(400, 0.9))}`);
out('');

out('3. Chip life (Arrhenius, Ea 0.7 eV, 10 years at an 85 C = 358 K junction; junction = radiator + 25 K)');
out(`   Halving step near 350 K: ${n1(oc.halvingStepK(350))} K; near 400 K: ${n1(oc.halvingStepK(400))} K`);
for (const t of [300, 320, 330, 340, 348, 360, 380, 400, 425]) {
  const life = oc.chipPhysicalLife(10, t + oc.JUNCTION_RISE_K, oc.CHIP_REF_JUNCTION_K);
  const hot = oc.chipPhysicalLife(10, t + oc.JUNCTION_RISE_K, oc.CHIP_REF_JUNCTION_HOT_K);
  out(`   radiator ${t} K: junction ${t + 25} K, life ${n1(life)} y (high-temperature chips ${n1(hot)} y); radiator ${n2(oc.radiatorAreaPerKw(t, 0.9) * 5)} kg/kW at 5 kg/m2`);
}
out('');

out('4. Growth versus ceiling (from 60 GW in 2026)');
const CEIL = [['Political cap, 1 TW', 1], ['1 % of land in solar, 18 TW', 18], ['10 % of land in solar, 180 TW', 180], ['All sunlight reaching Earth, 173,000 TW', 173000]];
out(`   1 % of land: Earth's land 1.49 x 10^14 m2 x 1 % x 12 W/m2 average per m2 of array land = ${n1(1.49e14 * 0.01 * 12 / 1e12)} TW (11.1 to 12.6 W/m2 gives ${n1(1.49e14 * 0.01 * 11.1 / 1e12)} to ${n1(1.49e14 * 0.01 * 12.6 / 1e12)})`);
out(`   Sunlight intercepted: pi x (6.371 x 10^6 m)^2 x 1,361 W/m2 = ${n0(Math.PI * 6.371e6 ** 2 * 1361 / 1e12)} TW`);
for (const g of [0.15, 0.3]) for (const [label, tw] of CEIL) {
  const y = oc.yearsToCeiling(tw, g);
  out(`   ${Math.round(g * 100)} %/yr, ${label}: ${n1(y)} years, ${Math.round(2026 + y)}`);
}
out(`   Ratio of ceilings 173,000 / 18 = ${n0(173000 / 18)}; extra years at 30 %: ${n1(oc.yearsToCeiling(173000, 0.3) - oc.yearsToCeiling(18, 0.3))}; at 15 %: ${n1(oc.yearsToCeiling(173000, 0.15) - oc.yearsToCeiling(18, 0.15))}`);
out(`   Energy growth from 36.5 % demand and 5 % efficiency: ${n1(oc.energyGrowthOf(0.365, 0.05) * 100)} %`);
out('');

out('5. Presets');
const rows = {};
for (const [k, p] of Object.entries(oc.PRESETS)) {
  const r = oc.evaluate(p.v);
  rows[k] = r;
  out(`   ${p.label}`);
  out(`     ground $/kW-yr: chips ${n0(r.ground.parts.chips)}, facility ${n0(r.ground.parts.facility)}, energy ${n0(r.ground.parts.energy)}; total ${n0(r.ground.total)}`);
  out(`     orbit $/kW-yr: chips ${n0(r.orbit.parts.chips)}, chip launch ${n0(r.orbit.parts.computeLaunch)}, infrastructure mass ${n0(r.orbit.parts.infraMass)}, hardware ${n0(r.orbit.parts.hardware)}, servicing ${n0(r.orbit.parts.servicing)}; total ${n0(r.orbit.total)}`);
  out(`     ratio ${n2(r.ratio)}; ${oc.bindingSentence(r)}`);
  out(`     mass ${n1(r.orbit.massKw)} kg/kW (radiator ${n2(r.orbit.mRad)}); launch multiplier ${n2(r.orbit.mult)}; chip life ${n1(r.orbit.orbitLife)} y (physical ${n1(r.orbit.physLife)} y)`);
  out(`     power in orbit $${n3(r.orbit.powerPerKwh)}/kWh; capex $${n0(r.orbit.capex)}/kW`);
  out(`     break-even launch $/kg: today's market ${r.breakEvenLaunchNow > 0 ? n0(r.breakEvenLaunchNow) : 'none'}; after the ceiling ${r.breakEvenLaunchAfter > 0 ? n0(r.breakEvenLaunchAfter) : 'none'}`);
  out(`     ceiling ${r.ceilingTW} TW at ${n1(r.energyGrowth * 100)} %: ${Number.isFinite(r.ceilingYear) ? r.ceilingYear.toFixed(1) : 'never'}; orbit breaks even ${Number.isFinite(r.breakEvenYear) ? r.breakEvenYear.toFixed(1) : 'never'}`);
  out(`     payback ${Number.isFinite(r.paybackNow) ? n1(r.paybackNow) : 'never'} y now, ${Number.isFinite(r.paybackAfter) ? n1(r.paybackAfter) : 'never'} y after the ceiling; market after ${n0(r.marketAfter)} $/kW-yr = $${n1(r.marketAfter * 1e6 / 1e9)} billion per GW-year`);
  out(`     at ${p.v.scaleGW} GW: radiator ${n1(r.totals.radiatorKm2)} km2, array ${n1(r.totals.arrayKm2)} km2, mass ${n0(r.totals.massT)} t, launches ${n0(r.totals.launches)}`);
}
out('');

out('6. Today preset with one condition changed at a time');
const t = oc.PRESETS.today.v;
const variants = [
  ['launch $200/kg', { launch: 200 }],
  ['chips last 12 years (and physically do)', { econLife: 12 }],
  ['launch $200/kg and chips 12 years', { launch: 200, econLife: 12 }],
  ['launch $200/kg, chips 12 years, $10/W chips', { launch: 200, econLife: 12, chipCost: 10 }],
  ['as above plus ground siting surcharge $0.05/kWh', { launch: 200, econLife: 12, chipCost: 10, surcharge: 0.05 }],
];
for (const [label, d] of variants) {
  const r = oc.evaluate({ ...t, ...d });
  out(`   ${label}: ground ${n0(r.ground.total)}, orbit ${n0(r.orbit.total)}, ratio ${n2(r.ratio)}; ${oc.bindingSentence(r)}`);
}
out('');

out('6b. Chip retirement schedule: same economic life on both sides, then orbit forced to retire early');
for (const P of [3000, 200]) {
  const a = oc.evaluate({ ...t, launch: P, econLife: 5 });
  const b = oc.evaluate({ ...t, launch: P, econLife: 12 });
  out(`   launch $${P}/kg: econ life 5 y ratio ${n2(a.ratio)}; 12 y ratio ${n2(b.ratio)}`);
}
for (const T of [330, 340, 350, 370]) {
  const r = oc.evaluate({ ...t, launch: 200, econLife: 12, radTemp: T });
  out(`   launch $200/kg, econ life 12 y, radiator ${T} K: physical life ${n1(r.orbit.physLife)} y, orbit life ${n1(r.orbit.orbitLife)} y, ratio ${n2(r.ratio)}`);
}
out('');

out('7. Latency and location');
for (const [k, l] of Object.entries(oc.LOCATIONS)) out(`   ${l.label}: round trip ${l.roundTripS} s, illumination ${l.illumination}, launch multiplier ${n2(oc.locationMultiplier(k))} (delta-v ${l.deltaVms} m/s at Isp ${oc.ROCKET_ISP_S} s)`);
out(`   Earth-Moon: 384,400 km / 299,792.458 km/s = ${n2(384400 / 299792.458)} s one way`);

const text = lines.join('\n') + '\n';
const outFile = join(root, 'docs', 'specs', 'space-data-centers-output.txt');

// ---------------------------------------------------------------------------------------------- diagrams
const esc = (x) => String(x).replace(/&/g, '&amp;').replace(/</g, '&lt;');
const FONT = 'font-family="DM Sans, system-ui, sans-serif" font-size="15"';
const head = (id, w, hgt, title, desc) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${hgt}" role="img" aria-labelledby="${id}-title ${id}-desc" ${FONT}>\n  <title id="${id}-title">${esc(title)}</title>\n  <desc id="${id}-desc">${esc(desc)}</desc>\n`;

function radiatorDiagram() {
  const X0 = 90; const X1 = 760; const T0 = 290; const T1 = 430;
  const xOf = (T) => X0 + ((T - T0) / (T1 - T0)) * (X1 - X0);
  const top = { y0: 80, y1: 230, max: 10 }; // kg/kW
  const bot = { y0: 290, y1: 440, max: 100, min: 0.1, log: true }; // years, log scale
  const yOf = (p, v) => (p.log
    ? p.y1 - ((Math.log10(v) - Math.log10(p.min)) / (Math.log10(p.max) - Math.log10(p.min))) * (p.y1 - p.y0)
    : p.y1 - (v / p.max) * (p.y1 - p.y0));
  // Points outside the panel are dropped, not clamped, so a curve never draws a false plateau.
  const pts = (fn, p) => { const a = []; for (let T = T0; T <= T1; T += 2) { const v = fn(T); if (v <= p.max && v >= (p.min ?? 0)) a.push(`${xOf(T).toFixed(1)},${yOf(p, v).toFixed(1)}`); } return a.join(' '); };
  const mass = (T) => oc.radiatorAreaPerKw(T, 0.9) * 5;
  const life = (T) => oc.chipPhysicalLife(10, T + 25, oc.CHIP_REF_JUNCTION_K);
  const lifeHot = (T) => oc.chipPhysicalLife(10, T + 25, oc.CHIP_REF_JUNCTION_HOT_K);
  const desc = `Two charts sharing a radiator temperature axis from 290 to 430 kelvin. Top: radiator mass per kilowatt at emissivity 0.9 and 5 kilograms per square metre falls from ${n1(mass(290))} kilograms at 290 K to ${n1(mass(330))} at 330 K and ${n1(mass(400))} at 400 K. Bottom: chip life, 10 years at an 85 C junction with the junction 25 K above the radiator, falls from ${n0(life(290))} years at 290 K to ${n0(life(330))} at 330 K and ${n1(life(400))} at 400 K; chips rated for a 150 C junction would last ${n0(lifeHot(400))} years at 400 K. Hotter radiators are lighter but wear chips out faster.`;
  let s = head('ocr', 800, 490, 'Radiator mass and chip life against radiator temperature', desc);
  s += `  <text x="20" y="30" fill="currentColor" font-size="18" font-weight="600">The central trade: hotter radiators are lighter, hotter chips die sooner</text>\n`;
  s += `  <text x="20" y="54" fill="currentColor" opacity="0.8">Emissivity 0.9, two faces, 5 kg/m² panels; chips rated 10 years at an 85 °C junction (Arrhenius, 0.7 eV)</text>\n`;
  for (const [p, lab, ticks, unit] of [[top, 'Radiator mass, kg per kW', [0, 5, 10], ''], [bot, 'Chip life, years (log scale)', [0.1, 1, 10, 100], '']]) {
    s += `  <g stroke="currentColor" stroke-width="1" opacity="0.35" fill="none"><line x1="${X0}" y1="${p.y0}" x2="${X0}" y2="${p.y1}"/><line x1="${X0}" y1="${p.y1}" x2="${X1}" y2="${p.y1}"/></g>\n`;
    for (const tk of ticks) s += `  <text x="${X0 - 8}" y="${yOf(p, tk) + 5}" text-anchor="end" fill="currentColor" opacity="0.75">${tk}${unit}</text><line x1="${X0}" y1="${yOf(p, tk)}" x2="${X1}" y2="${yOf(p, tk)}" stroke="currentColor" opacity="0.12"/>\n`;
    s += `  <text x="${X0 + 8}" y="${p.y0 - 8}" fill="currentColor" font-weight="600">${lab}</text>\n`;
  }
  s += `  <polyline points="${pts(mass, top)}" fill="none" style="stroke:var(--accent, #1f6f86)" stroke-width="3"/>\n`;
  s += `  <polyline points="${pts(life, bot)}" fill="none" style="stroke:var(--accent-2, #8a5a14)" stroke-width="3"/>\n`;
  s += `  <polyline points="${pts(lifeHot, bot)}" fill="none" style="stroke:var(--accent-2, #8a5a14)" stroke-width="2" stroke-dasharray="6 5"/>\n`;
  s += `  <text x="${xOf(372)}" y="${yOf(bot, 40)}" fill="currentColor" opacity="0.85">rated to 150 °C</text>\n`;
  s += `  <text x="${xOf(362)}" y="${yOf(bot, 0.5)}" fill="currentColor" opacity="0.85">today’s chips</text>\n`;
  const T330 = xOf(330);
  s += `  <line x1="${T330}" y1="${top.y0}" x2="${T330}" y2="${bot.y1}" stroke="currentColor" stroke-dasharray="3 4" opacity="0.6"/>\n`;
  s += `  <text x="${T330 + 6}" y="${top.y0 + 14}" fill="currentColor">330 K: ${n1(mass(330))} kg/kW, ${n0(life(330))} years</text>\n`;
  for (const T of [290, 310, 330, 350, 370, 390, 410, 430]) s += `  <text x="${xOf(T)}" y="${bot.y1 + 22}" text-anchor="middle" fill="currentColor" opacity="0.75">${T} K</text>\n`;
  return s + '</svg>\n';
}

function ceilingDiagram() {
  const X0 = 300; const X1 = 770; const Y0 = 2026; const Y1 = 2140;
  const xOf = (y) => X0 + ((Math.min(y, Y1) - Y0) / (Y1 - Y0)) * (X1 - X0);
  const items = CEIL.map(([label, tw]) => ({ label, tw, a: 2026 + oc.yearsToCeiling(tw, 0.3), b: 2026 + oc.yearsToCeiling(tw, 0.15) }));
  const desc = `For four ceilings on terrestrial data center power, the year demand reaches them when growth starts from 60 gigawatts in 2026. At 30 percent a year: ${items.map((i) => `${i.label} in ${Math.round(i.a)}`).join('; ')}. At 15 percent a year: ${items.map((i) => `${i.label} in ${Math.round(i.b)}`).join('; ')}. A ceiling 9,600 times larger buys 35 more years at 30 percent growth.`;
  let s = head('occ', 800, 330, 'When sustained growth reaches each terrestrial ceiling', desc);
  s += `  <text x="20" y="30" fill="currentColor" font-size="18" font-weight="600">A ceiling 9,600 times bigger buys 35 years</text>\n`;
  s += `  <text x="20" y="54" fill="currentColor" opacity="0.8">Year data center demand reaches each ceiling, from 60 GW in 2026</text>\n`;
  s += `  <circle cx="${X0 + 10}" cy="76" r="6" style="fill:var(--accent-2, #8a5a14)"/><text x="${X0 + 22}" y="81" fill="currentColor">30 % a year</text>\n`;
  s += `  <circle cx="${X0 + 140}" cy="76" r="6" style="fill:var(--accent, #1f6f86)"/><text x="${X0 + 152}" y="81" fill="currentColor">15 % a year</text>\n`;
  items.forEach((it, i) => {
    const y = 120 + i * 46;
    s += `  <text x="${X0 - 14}" y="${y + 5}" text-anchor="end" fill="currentColor">${esc(it.label)}</text>\n`;
    s += `  <line x1="${X0}" y1="${y}" x2="${X1}" y2="${y}" stroke="currentColor" opacity="0.12"/>\n`;
    s += `  <line x1="${xOf(it.a)}" y1="${y}" x2="${xOf(it.b)}" y2="${y}" stroke="currentColor" stroke-width="2" opacity="0.4"/>\n`;
    s += `  <circle cx="${xOf(it.a)}" cy="${y}" r="7" style="fill:var(--accent-2, #8a5a14)"/><text x="${xOf(it.a)}" y="${y - 12}" text-anchor="middle" fill="currentColor" font-size="13">${Math.round(it.a)}</text>\n`;
    s += `  <circle cx="${xOf(it.b)}" cy="${y}" r="7" style="fill:var(--accent, #1f6f86)"/><text x="${xOf(it.b)}" y="${y - 12}" text-anchor="middle" fill="currentColor" font-size="13">${it.b > Y1 ? `${Math.round(it.b)} →` : Math.round(it.b)}</text>\n`;
  });
  for (const yr of [2026, 2050, 2075, 2100, 2125]) s += `  <text x="${xOf(yr)}" y="314" text-anchor="middle" fill="currentColor" opacity="0.75">${yr}</text>\n`;
  return s + '</svg>\n';
}

function costDiagram() {
  const X0 = 110; const X1 = 640; // 160 px right of the longest bar for its total label
  const max = Math.max(...Object.values(rows).flatMap((r) => [r.ground.total, r.orbit.total]));
  const sc = (X1 - X0) / max;
  const COLORS = { chips: 'var(--accent-2, #8a5a14)', computeLaunch: 'color-mix(in srgb, var(--accent-2, #8a5a14) 50%, var(--surface, #fff))', infraMass: 'var(--accent, #1f6f86)', hardware: 'color-mix(in srgb, var(--accent, #1f6f86) 50%, var(--surface, #fff))', servicing: 'var(--muted, #55635f)', facility: 'color-mix(in srgb, var(--accent, #1f6f86) 50%, var(--surface, #fff))', energy: 'var(--accent, #1f6f86)' };
  const descParts = Object.entries(oc.PRESETS).map(([k, p]) => `${p.label}: ground $${n0(rows[k].ground.total)}, orbit $${n0(rows[k].orbit.total)} per kW-year, ${n2(rows[k].ratio)} times`);
  let s = head('ocs', 800, '__H__', 'Levelized cost per kW-year of compute on the ground and in orbit for three presets', `Stacked bars by cost component. ${descParts.join('. ')}. Chips dominate every bar once launch is cheap.`);
  s += `  <text x="20" y="30" fill="currentColor" font-size="18" font-weight="600">Once launch is cheap, the chips are the bill</text>\n`;
  s += `  <text x="20" y="54" fill="currentColor" opacity="0.8">Levelized cost per kW-year of IT power, the calculator’s three presets</text>\n`;
  let y = 84;
  for (const [k, p] of Object.entries(oc.PRESETS)) {
    const r = rows[k];
    s += `  <text x="20" y="${y + 6}" fill="currentColor" font-weight="600">${esc(p.label)}</text>\n`;
    for (const [side, parts, total] of [['Ground', oc.COMPONENTS.ground, r.ground], ['Orbit', oc.COMPONENTS.orbit, r.orbit]]) {
      y += 18;
      s += `  <text x="${X0 - 10}" y="${y + 15}" text-anchor="end" fill="currentColor">${side}</text>\n`;
      let x = X0;
      for (const c of parts) {
        const w = total.parts[c.key] * sc;
        if (w > 0.3) s += `  <rect x="${x.toFixed(1)}" y="${y}" width="${w.toFixed(1)}" height="22" style="fill:${COLORS[c.key]};stroke:var(--surface, #fff)"><title>${side}, ${esc(c.label)}: $${n0(total.parts[c.key])}</title></rect>\n`;
        x += w;
      }
      s += `  <text x="${x + 8}" y="${y + 16}" fill="currentColor" font-size="13">$${n0(total.total)}${side === 'Orbit' ? ` (${n2(r.ratio)}×)` : ''}</text>\n`;
      y += 22;
    }
    y += 26;
  }
  const leg = [['chips', 'Chips'], ['computeLaunch', 'Launching chips'], ['infraMass', 'Array, radiator, structure (orbit); energy (ground)'], ['hardware', 'Power hardware (orbit); facility (ground)'], ['servicing', 'Servicing']];
  leg.forEach(([k, lab], i) => {
    const lx = 20 + (i % 2) * 390; const ly = y + 4 + Math.floor(i / 2) * 24; // below every row, two columns
    s += `  <rect x="${lx}" y="${ly - 11}" width="13" height="13" style="fill:${COLORS[k]}"/><text x="${lx + 19}" y="${ly}" fill="currentColor" font-size="13">${esc(lab)}</text>\n`;
  });
  const height = y + 4 + Math.ceil(leg.length / 2) * 24 + 8;
  return s.replace('0 0 800 __H__', `0 0 800 ${height}`) + '</svg>\n';
}

const diagrams = { 'oc-radiator-trade.svg': radiatorDiagram(), 'oc-ceiling.svg': ceilingDiagram(), 'oc-cost-stack.svg': costDiagram() };
let stale = 0;
if (args.has('--check')) {
  const lf = (f) => readFileSync(f, 'utf8').replace(/\r\n/g, '\n'); // a CRLF checkout is not stale
  if (!existsSync(outFile) || lf(outFile) !== text) { console.error('stale: docs/specs/space-data-centers-output.txt'); stale++; }
  for (const [name, svg] of Object.entries(diagrams)) {
    const f = join(root, 'site', 'diagrams', name);
    if (!existsSync(f) || lf(f) !== svg) { console.error(`stale: site/diagrams/${name}`); stale++; }
  }
  if (stale) { console.error('Run: node scripts/analysis/orbit_compute.mjs --write-diagrams'); process.exit(1); }
  console.log('orbit_compute: output and diagrams current');
} else {
  writeFileSync(outFile, text);
  if (args.has('--write-diagrams')) for (const [name, svg] of Object.entries(diagrams)) writeFileSync(join(root, 'site', 'diagrams', name), svg);
  process.stdout.write(text);
}
